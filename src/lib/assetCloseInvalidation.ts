//   - "ยกมา" มาจากยอดปิดงวดเก่า (กติกาเดิม)
//   - "ค่าเสื่อมงวดนี้" คำนวณสดด้วยกติกาใหม่
// ทำให้ ยกมาของปี Y ไม่เท่ากับ ยกไปของปี Y-1 และหาสาเหตุยากมากเพราะตัวเลขดูสมเหตุสมผลทั้งคู่
//
// (เคสจริงที่เจอ: เปลี่ยนสูตร fallback เป็น FULL_ANNUAL_FIXED แล้วรายงานปี 2024
//  แสดงยกมา 225,597.26 ทั้งที่ยกไปของปี 2023 ที่คำนวณด้วยกติกาใหม่คือ 226,270.68 — คลาดกัน 1 วันพอดี)
//
// ล้างแล้วระบบจะสร้างใหม่ให้เองอัตโนมัติเมื่อเปิดหน้าทะเบียนหรือรายงานครั้งถัดไป
import { prisma } from "@/lib/prisma";

export async function invalidateAllAssetYearlyCloses(): Promise<number> {
  const result = await prisma.assetYearlyClose.deleteMany({});
  return result.count;
}
